import { NextResponse } from "next/server";
import fs from "fs/promises";
import path from "path";

function slugify(value) {
  return (value || "ai-app")
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, "")
    .trim()
    .replace(/\s+/g, "-")
    .slice(0, 40);
}

function isSafeRelativePath(filePath) {
  if (!filePath || typeof filePath !== "string") return false;
  if (path.isAbsolute(filePath)) return false;
  if (filePath.includes("..")) return false;
  if (filePath.includes("\0")) return false;
  return true;
}

export async function POST(req) {
  try {
    const body = await req.json();
    const { projectName = "ai-app", files = [] } = body || {};

    if (!Array.isArray(files) || files.length === 0) {
      return NextResponse.json(
        { error: "No files were provided." },
        { status: 400 }
      );
    }

    const safeProjectName = slugify(projectName) || "ai-app";

    // Writes into your project root /generated-projects/<project-name>/
    const projectRoot = process.cwd();
    const outputRoot = path.join(projectRoot, "generated-projects", safeProjectName);

    await fs.mkdir(outputRoot, { recursive: true });

    const writtenFiles = [];

    for (const file of files) {
      if (!file || typeof file.path !== "string" || typeof file.content !== "string") {
        continue;
      }

      if (!isSafeRelativePath(file.path)) {
        return NextResponse.json(
          { error: `Unsafe file path rejected: ${file.path}` },
          { status: 400 }
        );
      }

      const fullPath = path.join(outputRoot, file.path);
      const fullDir = path.dirname(fullPath);

      await fs.mkdir(fullDir, { recursive: true });
      await fs.writeFile(fullPath, file.content, "utf8");

      writtenFiles.push({
        path: file.path,
        fullPath,
      });
    }

    await fs.writeFile(
      path.join(outputRoot, "README.generated.md"),
      `# ${projectName}

This folder was generated by the AI Code Generator.

Files written:
${writtenFiles.map((file) => `- ${file.path}`).join("\n")}
`,
      "utf8"
    );

    return NextResponse.json({
      ok: true,
      projectName,
      outputRoot,
      writtenCount: writtenFiles.length,
      files: writtenFiles,
    });
  } catch (error) {
    console.error("write-files route error:", error);

    return NextResponse.json(
      { error: "Failed to write files." },
      { status: 500 }
    );
  }
}
